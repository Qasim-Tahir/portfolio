"""Generate indexed summaries from the same public content used by React."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def documents(data):
    profile = data['profile']
    header = '<!-- Generated by scripts/sync_content.py; edit content/portfolio.json. -->\n'
    result = {}
    for project in data['projects']:
        lines = [f"# {project['title']}", '', '## Overview', project['desc'], '', '## Technology',
                 ', '.join(project['tech']), '', '## Source and scope',
                 f"Reviewed {data['reviewed_at']}. Evidence classification: {project['evidence_status']}.",
                 project['repo'] or 'No public implementation is linked. The description is owner-reported.',
                 'No benchmark score, accuracy guarantee, or latency promise is asserted by this summary.', '',
                 '## Implementation', *project['details'], '']
        result[project['source'] + '.md'] = header + '\n'.join(lines)
    result['about.md'] = header + '\n'.join([
        f"# About {profile['name']}", '', '## Current role', profile['overview'], '',
        f"Role: {profile['role']} at {profile['employer']}.",
        'These employer responsibilities are owner-reported in the existing public portfolio; private employer artifacts have not been supplied.',
        '', '## Education', profile['education'], profile['education_status'], '',
        '## Work at The Services Tree', profile['work_summary'], '',
        *[f"### {item['title']}\n{item['desc']}\nEvidence classification: owner_reported.\n" for item in profile['highlights']],
        '## Areas of work', 'Retrieval-Augmented Generation, Large Language Models, knowledge graphs, multi-modal document processing and AI workflow automation.', ''])
    return result


def sync(check=False):
    data = json.loads((ROOT / 'content/portfolio.json').read_text())
    expected = documents(data)
    changed = []
    for name, text in expected.items():
        path = ROOT / 'docs' / name
        if not path.exists() or path.read_text() != text:
            changed.append(name)
            if not check:
                path.write_text(text)
    return changed


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    changed = sync(args.check)
    if args.check and changed:
        print('Indexed summaries differ from canonical content: ' + ', '.join(changed))
        raise SystemExit(1)
    print('Public and indexed summaries are synchronized.' if args.check else f'Generated {len(changed)} summaries.')


if __name__ == '__main__':
    main()
